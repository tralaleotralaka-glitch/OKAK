"""Small talk: приветствия, благодарности, «кто ты», помощь и шутки."""

from __future__ import annotations

import random
import re
from datetime import datetime

from .textutil import normalize

HELP_TEXT = (
    "Я OKAK — умный русскоязычный ассистент. Вот что я умею:\n"
    "• **Время и дата**: «который час», «какое сегодня число», «сколько времени в Токио»\n"
    "• **Дни до события**: «сколько дней до нового года», «сколько дней до 8 марта»\n"
    "• **Математика**: «2+2*3», «корень из 144», «15% от 480», «реши x^2 - 5x + 6 = 0», "
    "«производная от x^3», «интеграл от 2x»\n"
    "• **Знания**: история, литература, наука, география, технологии, столицы стран\n"
    "• **Шутки**: «расскажи анекдот»"
)

JOKES = [
    "Почему программисты путают Хэллоуин и Рождество? Потому что Oct 31 == Dec 25.",
    "— Сколько будет 2 + 2? — Зависит от того, в какой системе счисления ты спрашиваешь.",
    "Как называется игрок, который не умеет считать? Нулевой.",
    "Что сказал ноль восьмёрке? «Классный ремень!»",
    "Заходит математик в бар. Бармен спрашивает: «Что будете?» — «Ничего, я уже на пределе».",
    "Почему компьютер простудился? Потому что сидел рядом с открытым окном… и Windows.",
]

_GREET_RE = re.compile(r"^(привет|здравствуй|здравствуйте|хай|хеллоу|hello|hi|приветик|добрый\s+(день|вечер|утро)|доброе утро|добрый)\b")
_THANKS_RE = re.compile(r"спасибо|благодарю|thanks|сенкс")
_BYE_RE = re.compile(r"^(пока|до свидания|до встречи|бай|прощай|увидимся|спокойной ночи)\b")
_WHO_RE = re.compile(r"кто ты|ты кто|как тебя зовут|как тебя называть|твое имя|твоё имя|как ты называешься|who are you")
_HELP_RE = re.compile(r"что ты умеешь|что умеешь|что ты можешь|что можешь|помощь|help|команды|возможности|что ты знаешь")
_HOW_RE = re.compile(r"как дела|как ты|как жизнь|как поживаешь|как настроение")
_JOKE_RE = re.compile(r"шутк|анекдот|смешн|рассмеш|пошути")


def _greeting_for_time(now: datetime) -> str:
    hour = now.hour
    if 5 <= hour < 12:
        return "Доброе утро"
    if 12 <= hour < 18:
        return "Добрый день"
    if 18 <= hour < 23:
        return "Добрый вечер"
    return "Доброй ночи"


def answer_smalltalk(message: str, now: datetime) -> str | None:
    text = normalize(message).strip(" !?.,")
    if not text:
        return "Напишите вопрос — я постараюсь помочь. Например: «который час» или «корень из 81»."
    if _GREET_RE.search(text):
        return f"{_greeting_for_time(now)}! Чем могу помочь? 🙂"
    if _THANKS_RE.search(text):
        return random.choice(["Пожалуйста! Обращайтесь ещё 🙂", "Рад помочь!", "Всегда пожалуйста."])
    if _BYE_RE.search(text):
        return "До встречи! Возвращайтесь с новыми вопросами. 👋"
    if _WHO_RE.search(text):
        return ("Меня зовут OKAK. Я отвечаю на вопросы по-русски: знаю время и дату, "
                "считаю математику, решаю уравнения и рассказываю о многих областях знаний.")
    if _HELP_RE.search(text):
        return HELP_TEXT
    if _HOW_RE.search(text):
        return random.choice([
            "Отлично, спасибо! Готов к вопросам. А у вас как?",
            "Всё хорошо, работаю в полную мощность. Чем займёмся?",
        ])
    if _JOKE_RE.search(text):
        return random.choice(JOKES)
    return None
